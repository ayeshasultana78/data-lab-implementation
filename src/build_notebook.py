md("### Exercise 4.3 - Hypothesis test: does discounting change order quantity?")
code("""
disc = df.loc[df.discount_pct > 0, "quantity"]
nodisc = df.loc[df.discount_pct == 0, "quantity"]
t, p = stats.ttest_ind(disc, nodisc, equal_var=False)
print(f"Mean quantity with discount   : {disc.mean():.3f}")
print(f"Mean quantity without discount: {nodisc.mean():.3f}")
print(f"Welch t-test: t = {t:.3f}, p = {p:.4f}")
print("Conclusion:", "significant difference" if p < 0.05 else "no significant difference at 5% level")
""")
md("### Exercise 4.4 - Holiday-season effect (Nov-Dec vs rest of year)")
code("""
df["holiday_season"] = df["order_date"].dt.month.isin([11, 12])
daily = df.groupby(["order_date", "holiday_season"])["revenue"].sum().reset_index()
season = daily.groupby("holiday_season")["revenue"].mean()
t2, p2 = stats.ttest_ind(daily.loc[daily.holiday_season, "revenue"],
                         daily.loc[~daily.holiday_season, "revenue"], equal_var=False)
print("Average daily revenue:"); print(season.rename({True: "Nov-Dec", False: "Jan-Oct"}))
print(f"\\nUplift: {season[True] / season[False] - 1:.1%}   (Welch t = {t2:.2f}, p = {p2:.4g})")
""")
